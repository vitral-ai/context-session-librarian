class WorkloadCodecTests(unittest.TestCase):
    def test_missing_optional_helper_refuses_without_a_key(self):
        with tempfile.TemporaryDirectory(prefix='workload-no-helper-') as directory:
            root = Path(directory)/'state'
            with patch('csl_workload_identity.shutil.which', return_value=None):
                with self.assertRaisesRegex(SyncError, '^workload_crypto_unavailable$'):
                    WorkloadKey(root)
            self.assertFalse((root/'workload-ed25519.pem').exists())

    def test_metadata_bounds_run_before_pattern_scans(self):
        detector = Mock()
        with patch('csl_workload_identity.PATTERNS', [('fixture', detector, 0)]):
            with self.assertRaises(SyncError): metadata({**LOCATION, 'label': 'x'*129})
        detector.search.assert_not_called()

    def test_utf8_metadata_canonical_digest_and_closed_schema(self):
        clean, digest = metadata(LOCATION)
        self.assertEqual(digest, META_SHA)
        self.assertEqual(canonical(clean).decode(),
            '{"cluster":"local-kind","label":"W7 workload caf\u00e9","namespace":"test",'
            '"provider":"kubernetes","replica":"fixture-1","workload":"fixture-job"}')
        self.assertEqual(metadata(dict(reversed(list(LOCATION.items())))), (clean, digest))
        for field, value in [('label', ''), ('label', ' bad'), ('label', 'bad\n'),
                             ('label', '\u00e9'*65), ('provider', 'Kubernetes'), ('replica', '../x?'),
                             ('cluster', 'a'*129), ('namespace', 4), ('workload', '\u00e9'),
                             ('label', 'sk-proj-'+'Z'*32), ('cluster', 'ghp_'+'Z'*24)]:
            with self.subTest(field=field, value=value), self.assertRaises(SyncError):
                metadata({**LOCATION, field: value})
        with self.assertRaises(SyncError): metadata({**LOCATION, 'owner': 'untrusted'})
        with self.assertRaises(SyncError): metadata({k: v for k, v in LOCATION.items() if k != 'replica'})

    def test_workload_device_refresh_payload_vectors(self):
        jwk, thumb = public_key(PUBLIC)
        self.assertEqual(jwk['x'], '11qYAYKxCrfVS_7TyWQHOg7hcvPapiMlrwIaaPcHURo')
        self.assertEqual(thumb.hex(), '90facafea9b1556698540f70c0117a22ea37bd5cf3ed3c47093c1707282b4b89')
        for kind, credential, nonce, length, digest, _ in VECTORS:
            payload = proof_message(ISSUER, credential, nonce, thumb, bytes.fromhex(META_SHA), refresh=kind == 'refresh')
            self.assertEqual(len(payload), length)
            self.assertEqual(hashlib.sha256(payload).hexdigest(), digest)
            self.assertNotIn(credential.encode(), payload)
            self.assertIn(b'vitral-workload-collector', payload)
            self.assertNotIn(b'vitral-host-agent', payload)
        with self.assertRaises(SyncError): proof_message('http://bad/native-auth/v1', 'fixture', nonce, thumb, thumb)
        with self.assertRaises(SyncError): proof_message(ISSUER+'/other', 'fixture', nonce, thumb, thumb)
        with self.assertRaises(SyncError): proof_message(ISSUER, 'fixture', b'x', thumb, thumb)

    def test_base64url_requires_canonical_unpadded_fixed_length(self):
        self.assertEqual(unb64(b64(PUBLIC), 32), PUBLIC)
        for value in (b64(PUBLIC)+'=', ' '+b64(PUBLIC), b64(PUBLIC)[:-1], 'A'*42+'B', None):
            with self.subTest(value=value), self.assertRaises(SyncError): unb64(value, 32)


@unittest.skipUnless(shutil.which('openssl'), 'OpenSSL needed for optional workload key helper')
class WorkloadKeyTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory(prefix='workload-key-fixture-')
        self.addCleanup(self.tmp.cleanup)
        self.root = Path(self.tmp.name)
        self.key = WorkloadKey(self.root/'state')

    def seed_key(self):
        der = bytes.fromhex('302e020100300506032b657004220420')+SEED
        pem = b'-----BEGIN PRIVATE KEY-----\n'+base64.b64encode(der)+b'\n-----END PRIVATE KEY-----\n'
        self.key.path.write_bytes(pem); self.key.path.chmod(0o600)

    def test_openssl_signatures_match_independent_vectors_and_never_rotate(self):
        self.seed_key()
        before = self.key.path.read_bytes()
        jwk, thumb = self.key.ensure()
        self.assertEqual(jwk, public_key(PUBLIC)[0])
        for kind, credential, nonce, _, _, expected in VECTORS:
            self.assertEqual(self.key.proof(ISSUER, credential, nonce, bytes.fromhex(META_SHA),
                expected_thumbprint=thumb, refresh=kind == 'refresh'), expected)
        self.assertEqual(self.key.path.read_bytes(), before)
        self.assertEqual(list(self.key.root.glob('.proof-*')), [])
        with self.assertRaisesRegex(SyncError, '^workload_key_binding_changed$'):
            self.key.proof(ISSUER, 'fixture', bytes(32), bytes(32), expected_thumbprint=bytes(32))

    def test_generated_key_persists_with_private_modes(self):
        first = self.key.ensure()
        self.assertEqual(WorkloadKey(self.key.root).ensure(), first)
        self.assertEqual(self.key.root.stat().st_mode & 0o777, 0o700)
        self.assertEqual(self.key.path.stat().st_mode & 0o777, 0o600)

    def test_racing_initializer_cannot_replace_an_existing_identity(self):
        def raced(*arguments):
            self.seed_key()
            return b'never-written-competing-key'
        with patch.object(self.key, '_run', side_effect=raced):
            with self.assertRaisesRegex(SyncError, '^workload_key_storage_refused$'):
                self.key.ensure()
        self.assertEqual(self.key.public()[0], public_key(PUBLIC)[0])

    def test_shared_existing_directory_is_not_chmodded(self):
        shared = self.root/'shared'; shared.mkdir(); shared.chmod(0o755)
        with self.assertRaisesRegex(SyncError, '^workload_key_storage_refused$'):
            WorkloadKey(shared)
        self.assertEqual(shared.stat().st_mode & 0o777, 0o755)

    def test_malformed_public_symlink_and_permissive_key_refuse_without_replacement(self):
        self.seed_key(); original = self.key.path.read_bytes()
        self.key.path.chmod(0o644)
        with self.assertRaises(SyncError): self.key.ensure()
        self.assertEqual(self.key.path.read_bytes(), original)
        self.key.path.chmod(0o600); self.key.path.write_bytes(b'invalid')
        with self.assertRaises(SyncError): self.key.ensure()
        self.assertEqual(self.key.path.read_bytes(), b'invalid')
        self.key.path.unlink(); other = self.root/'not-a-key'; other.write_bytes(b'not-read')
        self.key.path.symlink_to(other)
        with self.assertRaises(SyncError): self.key.ensure()
        self.assertEqual(other.read_bytes(), b'not-read')

    def test_child_environment_and_arguments_never_contain_fixture_credentials(self):
        self.seed_key(); _, thumb = self.key.public()
        real_run, calls = subprocess.run, []
        def record(args, **kwargs):
            calls.append((args, copy.deepcopy(kwargs.get('env'))))
            return real_run(args, **kwargs)
        canary = 'SYNTHETIC-CREDENTIAL-DO-NOT-LOG'
        with patch.dict(os.environ, {'AWS_ACCESS_KEY_ID': canary, 'OPENSSL_CONF': '/not/read', 'FAKE_AUTH': canary}), \
                patch('csl_workload_identity.subprocess.run', side_effect=record):
            self.key.proof(ISSUER, canary, bytes(32), bytes(32), expected_thumbprint=thumb)
        self.assertNotIn(canary, repr(calls))
        for _, env in calls: self.assertEqual(set(env), {'HOME', 'PATH', 'LANG'})
        self.assertEqual(list(self.key.root.glob('.proof-*')), [])

    def test_helper_timeout_is_scrubbed_and_removes_payload(self):
        self.seed_key(); _, thumb = self.key.public()
        with patch.object(self.key, 'public', return_value=({}, thumb)), \
                patch('csl_workload_identity.subprocess.run', side_effect=subprocess.TimeoutExpired('fixture-secret', 5)):
            with self.assertRaisesRegex(SyncError, '^workload_crypto_unavailable$') as refusal:
                self.key.proof(ISSUER, 'fixture', bytes(32), bytes(32), expected_thumbprint=thumb)
        self.assertIsNone(refusal.exception.__context__)
        self.assertEqual(list(self.key.root.glob('.proof-*')), [])


